-- 6. NEW RPC: admin_list_audit_logs — filter, search, pagination
-- ======================================================================
create or replace function public.admin_list_audit_logs(
  p_action     text default null,
  p_date_from  date default null,
  p_date_to    date default null,
  p_search     text default null,
  p_page       int  default 1,
  p_limit      int  default 25
)
returns table (
  id                uuid,
  action            text,
  admin_email       text,
  activation_code_id uuid,
  activation_id     uuid,
  device_id         text,
  status            text,
  reason            text,
  user_agent        text,
  details           jsonb,
  created_at        timestamptz,
  total_count       bigint
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_uid uuid := auth.uid();
  v_is_admin  boolean;
  v_offset    int;
begin
  select exists(select 1 from public.pkg_admins where user_id = v_admin_uid) into v_is_admin;
  if not v_is_admin then
    raise exception 'UNAUTHORIZED: pemanggil bukan admin terdaftar' using errcode = '42501';
  end if;

  v_offset := (p_page - 1) * p_limit;

  return query
  select
    a.id,
    a.action,
    au.email as admin_email,
    a.activation_code_id,
    coalesce(a.activation_id, a.activation_code_id) as activation_id,
    a.device_id,
    a.status,
    a.reason,
    a.user_agent,
    a.details,
    a.created_at,
    count(*) over() as total_count
  from public.pkg_activation_audit_logs a
  left join auth.users au on au.id = a.admin_user_id
  where (p_action is null or a.action = p_action)
    and (p_date_from is null or a.created_at >= p_date_from)
    and (p_date_to is null or a.created_at < (p_date_to + interval '1 day'))
    and (
      p_search is null or
      a.status ilike '%' || p_search || '%' or
      a.reason ilike '%' || p_search || '%' or
      a.device_id ilike '%' || p_search || '%' or
      coalesce(au.email, '') ilike '%' || p_search || '%' or
      a.action ilike '%' || p_search || '%'
    )
  order by a.created_at desc
  limit p_limit offset v_offset;
end;
$$;

