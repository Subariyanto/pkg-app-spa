create or replace function public._cleanup_old_rate_limits()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_deleted integer;
begin
  delete from public.pkg_rate_limits
  where last_attempt < now() - interval '1 hour'
  returning id into v_deleted;
