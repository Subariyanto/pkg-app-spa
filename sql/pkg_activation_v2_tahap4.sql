-- ======================================================================
-- 3. HELPER FUNCTION: _check_rate_limit — server-side rate limiter
-- Returns true if request is allowed, false if rate-limited.
-- Also records the attempt.
-- ======================================================================
create or replace function public._check_rate_limit(
  p_session_key  text,
  p_ip_address   inet default null,
  p_code_hash    text default null
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_existing   record;
  v_now        timestamptz := now();
  v_window     timestamptz := v_now - interval '10 minutes';
  v_max_attempts int := 5;
begin
  -- Check if currently locked
  select * into v_existing
  from public.pkg_rate_limits
  where session_key = p_session_key
    and last_attempt > v_window
  order by last_attempt desc
  limit 1;

  if found then
    -- Check lock
    if v_existing.locked_until is not null and v_existing.locked_until > v_now then
      return false;
    end if;

    -- Check attempt count in window
    if v_existing.attempt_count >= v_max_attempts and v_existing.first_attempt > v_window then
      -- Lock for 10 minutes from last attempt
      update public.pkg_rate_limits
      set locked_until = v_now + interval '10 minutes',
          last_attempt = v_now,
          attempt_count = attempt_count + 1
      where id = v_existing.id;
      return false;
    end if;

    -- Increment attempt
    if v_existing.first_attempt > v_window then
      -- Still in window, increment
      update public.pkg_rate_limits
      set attempt_count = attempt_count + 1,
          last_attempt = v_now,
          code_attempted = coalesce(p_code_hash, v_existing.code_attempted)
      where id = v_existing.id;
    else
      -- Window expired, reset
      update public.pkg_rate_limits
      set attempt_count = 1,
          first_attempt = v_now,
          last_attempt = v_now,
          locked_until = null,
          code_attempted = p_code_hash
      where id = v_existing.id;
    end if;
  else
    -- No existing record, create new
    insert into public.pkg_rate_limits (session_key, ip_address, code_attempted, attempt_count, first_attempt, last_attempt)
    values (p_session_key, p_ip_address, p_code_hash, 1, v_now, v_now);
  end if;

  return true;
end;
$$;

