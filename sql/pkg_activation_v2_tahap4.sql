-- 5. ENHANCED: activate_pkg_code — add rate limiting + audit logging
-- ======================================================================
drop function if exists public.activate_pkg_code(text, text, text, text, text, text, text, text, jsonb);

create or replace function public.activate_pkg_code(
  p_code              text,
  p_device_id         text,
  p_nama_pengguna     text default null,
  p_username          text default null,
  p_madrasah          text default null,
  p_kabupaten         text default null,
  p_role              text default null,
  p_device_info       text default null,
  p_device_public_key jsonb default null
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code_hash     text;
  v_code_row      record;
  v_session_key   text := coalesce(p_device_id, '');
  v_rate_ok       boolean;
  v_ip            inet := null;
  v_user_agent    text := null;
  v_result        text;
begin
  -- Hash the code for lookup
  v_code_hash := encode(digest(p_code, 'sha256'), 'hex');

  -- Rate limit check
  v_rate_ok := public._check_rate_limit(v_session_key, v_ip, v_code_hash);
  if not v_rate_ok then
    -- Audit log: rate limited
    insert into public.pkg_activation_audit_logs (
      action, device_id, status, reason, user_agent, ip_address,
      details
    ) values (
      'RATE_LIMITED', p_device_id, 'RATE_LIMITED',
      'Rate limit exceeded: 5+ failed attempts in 10 minutes',
      v_user_agent, v_ip,
      jsonb_build_object('session_key', v_session_key, 'code_hint', right(p_code, 4))
    );
    return 'RATE_LIMITED';
  end if;

  -- Validate code format (basic check)
  if p_code is null or length(p_code) < 10 then
    insert into public.pkg_activation_audit_logs (
      action, device_id, status, reason, user_agent, ip_address,
      details
    ) values (
      'FAILED_ACTIVATION', p_device_id, 'INVALID_CODE',
      'Code format invalid (too short)',
      v_user_agent, v_ip,
      jsonb_build_object('code_hint', right(coalesce(p_code, ''), 4))
    );
    return 'INVALID_CODE';
  end if;

  -- Look up code by hash
  select * into v_code_row
  from public.pkg_activation_codes
  where code_hash = v_code_hash
  for update;  -- row-level lock prevents race condition

  if not found then
    -- Code not found
    insert into public.pkg_activation_audit_logs (
      action, device_id, status, reason, user_agent, ip_address,
      details
    ) values (
      'FAILED_ACTIVATION', p_device_id, 'INVALID_CODE',
      'Code not found in database',
      v_user_agent, v_ip,
      jsonb_build_object('code_hint', right(p_code, 4))
    );
    return 'INVALID_CODE';
  end if;

  -- Check if revoked
  if v_code_row.status = 'revoked' then
    insert into public.pkg_activation_audit_logs (
      action, activation_code_id, device_id, status, reason,
      user_agent, ip_address, details
    ) values (
      'FAILED_ACTIVATION', v_code_row.id, p_device_id, 'REVOKED',
      'Code has been revoked',
      v_user_agent, v_ip,
      jsonb_build_object('code_hint', v_code_row.code_hint)
    );
    return 'REVOKED';
  end if;

  -- Check if already used
  if v_code_row.status = 'activated' then
    insert into public.pkg_activation_audit_logs (
      action, activation_code_id, device_id, status, reason,
      user_agent, ip_address, details
    ) values (
      'FAILED_ACTIVATION', v_code_row.id, p_device_id, 'ALREADY_USED',
      'Code already activated by another device',
      v_user_agent, v_ip,
      jsonb_build_object('code_hint', v_code_row.code_hint, 'existing_device', v_code_row.device_id)
    );
    return 'ALREADY_USED';
  end if;

  -- Code is valid and unused — activate it
  update public.pkg_activation_codes
  set
    status              = 'activated',
    activated_at        = now(),
    activated_by        = p_device_id,
    device_id           = p_device_id,
    device_info         = p_device_info,
    device_public_key   = p_device_public_key,
    device_key_created_at = case when p_device_public_key is not null then now() else device_key_created_at end,
    nama_pengguna       = coalesce(p_nama_pengguna, nama_pengguna),
    username            = coalesce(p_username, username),
    madrasah            = coalesce(p_madrasah, madrasah),
    kabupaten           = coalesce(p_kabupaten, kabupaten),
    role                = coalesce(p_role, role)
  where id = v_code_row.id;

  -- Clear rate limit on success
  perform public._clear_rate_limit(v_session_key);

  -- Audit log: successful activation
  insert into public.pkg_activation_audit_logs (
    action, activation_code_id, device_id, status, reason,
    user_agent, ip_address, details
  ) values (
    'ACTIVATE_CODE', v_code_row.id, p_device_id, 'ACTIVATED',
    'Code successfully activated',
    v_user_agent, v_ip,
    jsonb_build_object(
      'code_hint', v_code_row.code_hint,
      'nama_pengguna', coalesce(p_nama_pengguna, v_code_row.nama_pengguna),
      'madrasah', coalesce(p_madrasah, v_code_row.madrasah),
      'kabupaten', coalesce(p_kabupaten, v_code_row.kabupaten),
      'role', coalesce(p_role, v_code_row.role),
      'has_device_key', p_device_public_key is not null
    )
  );

  return 'ACTIVATED';
end;
$$;

