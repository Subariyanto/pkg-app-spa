-- 11. ENHANCED: admin_revoke_activation_code — add audit log with reason
-- ======================================================================
-- (Already logs in Tahap 2, but now we have expanded action constraint)
-- Re-create to include revoked_reason column
-- Drop BOTH old signatures: Tahap 2 had (uuid), we need to also drop that
-- to avoid ambiguity with the new 2-arg version.
drop function if exists public.admin_revoke_activation_code(uuid);
drop function if exists public.admin_revoke_activation_code(uuid, text);

create or replace function public.admin_revoke_activation_code(
  p_code_id  uuid,
  p_reason   text default null
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_uid uuid := auth.uid();
  v_is_admin  boolean;
  v_code_row  record;
begin
  select exists(select 1 from public.pkg_admins where user_id = v_admin_uid) into v_is_admin;
  if not v_is_admin then
    raise exception 'UNAUTHORIZED' using errcode = '42501';
  end if;

  select * into v_code_row
  from public.pkg_activation_codes
  where id = p_code_id
  for update;

  if not found then
    raise exception 'NOT_FOUND: kode aktivasi tidak ditemukan';
  end if;

  if v_code_row.status = 'revoked' then
    raise exception 'ALREADY_REVOKED';
  end if;

  update public.pkg_activation_codes
  set status = 'revoked',
      revoked_at = now(),
      revoked_by = v_admin_uid,
      revoked_reason = coalesce(p_reason, 'Manual revocation by admin')
  where id = p_code_id;

  -- Audit log
  insert into public.pkg_activation_audit_logs (
    admin_user_id, action, activation_code_id, status, reason, details
  ) values (
    v_admin_uid, 'REVOKE_CODE', p_code_id, 'REVOKED',
    coalesce(p_reason, 'Manual revocation'),
    jsonb_build_object(
      'code_hint', v_code_row.code_hint,
      'previous_status', v_code_row.status,
      'revoked_reason', coalesce(p_reason, 'Manual revocation by admin')
    )
  );

  return 'REVOKED';
end;
$$;

