create or replace function public.admin_activation_stats_v2()
returns table (
  total_codes      bigint,
  unused_codes     bigint,
  activated_codes  bigint,
  revoked_codes    bigint,
  activated_today  bigint,
  activated_30d     bigint,
  device_replacements bigint,
  failed_attempts  bigint
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_uid uuid := auth.uid();
  v_is_admin  boolean;
begin
  select exists(select 1 from public.pkg_admins where user_id = v_admin_uid) into v_is_admin;
  if not v_is_admin then
    raise exception 'UNAUTHORIZED' using errcode = '42501';
  end if;

  return query
  select
    (select count(*) from public.pkg_activation_codes) as total_codes,
    (select count(*) from public.pkg_activation_codes where status = 'unused') as unused_codes,
    (select count(*) from public.pkg_activation_codes where status = 'activated') as activated_codes,
    (select count(*) from public.pkg_activation_codes where status = 'revoked') as revoked_codes,
    (select count(*) from public.pkg_activation_codes where activated_at >= current_date) as activated_today,
    (select count(*) from public.pkg_activation_codes where activated_at >= now() - interval '30 days') as activated_30d,
    (select count(*) from public.pkg_activation_codes where replacement_for is not null) as device_replacements,
    (select count(*) from public.pkg_activation_audit_logs where action = 'FAILED_ACTIVATION' and created_at >= now() - interval '24 hours') as failed_attempts;
end;
$$;

